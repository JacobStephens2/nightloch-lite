#!/usr/bin/env zsh
# Slice 1: ensure tfvars, resolve Cloudflare zone id, tofu plan|apply via bws.
# Never prints secret values. Run in a shell where you can bws-auth if needed:
#   cd ~/GitHub/JacobStephens2/nightloch-lite && ./scripts/slice1-up.sh plan
#   ./scripts/slice1-up.sh apply

set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
TF_DIR="$ROOT/infra/opentofu"
TFVARS="$TF_DIR/terraform.tfvars"
ACTION="${1:-plan}"

if [[ "$ACTION" != "plan" && "$ACTION" != "apply" ]]; then
  print -u2 "Usage: $0 plan|apply"
  exit 2
fi

# Ensure PATH has tofu + bws
path=("$HOME/.local/bin" /opt/homebrew/bin /usr/local/bin $path)

if ! command -v tofu >/dev/null; then
  print -u2 "tofu not found on PATH"
  exit 1
fi
if ! command -v bws >/dev/null; then
  print -u2 "bws not found on PATH (expected ~/.local/bin/bws)"
  exit 1
fi

# shellcheck disable=SC1090
[[ -f "$HOME/.zshrc" ]] && source "$HOME/.zshrc" 2>/dev/null || true

: "${BWS_PROJECT_ID:=19dfca05-8d2f-491b-981a-b4950159eb9c}"
export BWS_PROJECT_ID

if [[ -z "${BWS_ACCESS_TOKEN:-}" ]]; then
  if typeset -f bws-auth >/dev/null; then
    bws-auth || exit 1
  else
    print -u2 "BWS_ACCESS_TOKEN not set. Run: source ~/.zshrc && bws-auth"
    exit 1
  fi
fi

PUBKEY="${SSH_PUBLIC_KEY_PATH:-$HOME/.ssh/id_ed25519.pub}"
if [[ ! -f "$PUBKEY" ]]; then
  print -u2 "SSH public key not found at $PUBKEY"
  exit 1
fi

# Fetch zone id without printing tokens (only the zone id goes to stdout of python)
ZONE_ID="$(
  bws run --project-id "$BWS_PROJECT_ID" --shell zsh -- \
    zsh -c '
      set -euo pipefail
      if [[ -z "${CLOUDFLARE_API_TOKEN:-}" ]]; then
        print -u2 "CLOUDFLARE_API_TOKEN missing in injected env"
        exit 1
      fi
      curl -fsS \
        -H "Authorization: Bearer ${CLOUDFLARE_API_TOKEN}" \
        -H "Content-Type: application/json" \
        "https://api.cloudflare.com/client/v4/zones?name=nightloch.app" \
      | python3 -c "
import json,sys
r=json.load(sys.stdin)
if not r.get(\"success\") or not r.get(\"result\"):
    print(r.get(\"errors\") or r, file=sys.stderr)
    sys.exit(1)
print(r[\"result\"][0][\"id\"])
"
    '
)"

if [[ -z "$ZONE_ID" || ${#ZONE_ID} -lt 32 ]]; then
  print -u2 "Failed to resolve Cloudflare zone id for nightloch.app"
  exit 1
fi

print "Cloudflare zone id: $ZONE_ID"

# Write/overwrite non-secret tfvars (tokens stay in env via bws, not in this file)
cat > "$TFVARS" <<EOF
# Generated by scripts/slice1-up.sh — no API tokens in this file
ssh_public_key_path = "$PUBKEY"
cloudflare_zone_id  = "$ZONE_ID"
region              = "nyc3"
size                = "s-1vcpu-2gb"
image               = "ubuntu-24-04-x64"
admin_user          = "nightloch"
staging_host        = "lite.nightloch.app"
enable_dns_records  = true
manage_resend_dns   = false
EOF

print "Wrote $TFVARS (no secrets)"

cd "$TF_DIR"
tofu init -input=false

if [[ "$ACTION" == "plan" ]]; then
  bws run --project-id "$BWS_PROJECT_ID" --shell zsh -- \
    tofu plan -input=false -out=tfplan
  print "Plan saved to $TF_DIR/tfplan"
  print "Review, then: ./scripts/slice1-up.sh apply"
else
  if [[ -f tfplan ]]; then
    bws run --project-id "$BWS_PROJECT_ID" --shell zsh -- \
      tofu apply -input=false tfplan
  else
    bws run --project-id "$BWS_PROJECT_ID" --shell zsh -- \
      tofu apply -input=false -auto-approve
  fi
  print "--- non-secret outputs ---"
  tofu output -json 2>/dev/null | python3 -c '
import json,sys
o=json.load(sys.stdin)
for k in ("droplet_ipv4","staging_url","ssh_example","dns_records","next_steps"):
    if k in o:
        v=o[k].get("value")
        print(f"{k}: {v}")
print("(console_password: run tofu output -raw console_password locally; store in password manager)")
'
fi
